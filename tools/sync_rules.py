"""Copy the engine's rules.json into the Chrome extension as rules.js, so both use the same rule list.

Run after editing injectguard/rules.json:  python tools/sync_rules.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rules = json.loads((root / "injectguard" / "rules.json").read_text(encoding="utf-8"))
out = root / "extension" / "rules.js"
out.write_text("// GENERATED by tools/sync_rules.py from injectguard/rules.json - do not edit by hand.\n"
               "self.IG_RULES = " + json.dumps(rules, indent=1) + ";\n", encoding="utf-8")
print(f"wrote {out} ({len(rules['phrase_rules'])} phrase rules)")
